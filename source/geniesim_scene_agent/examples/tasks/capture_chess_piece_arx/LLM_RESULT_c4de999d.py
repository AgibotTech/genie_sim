# Global timeout: if scene generation takes longer than this, abort with fallback
SCENE_GEN_TIMEOUT_SEC = 5.0

class SceneGenTimeout(Exception):
    """Raised when scene generation exceeds the time limit."""
    pass

def _timeout_handler(signum, frame):
    raise SceneGenTimeout(f"Scene generation exceeded {SCENE_GEN_TIMEOUT_SEC}s limit")

def _run_with_timeout(func, fallback_func):
    """
    Run a function with a timeout. If it takes too long, call the fallback function.
    """
    old_handler = signal.signal(signal.SIGALRM, _timeout_handler)
    signal.alarm(int(SCENE_GEN_TIMEOUT_SEC))
    try:
        result = func()
    except SceneGenTimeout:
        print(f"[TIMEOUT] Scene generation timed out after {SCENE_GEN_TIMEOUT_SEC}s, using fallback")
        result = fallback_func()
    finally:
        signal.alarm(0)
        signal.signal(signal.SIGALRM, old_handler)
    return result

