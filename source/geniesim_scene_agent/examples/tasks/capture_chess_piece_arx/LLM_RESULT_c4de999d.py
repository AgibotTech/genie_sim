def are_squares_adjacent(square1: str, square2: str) -> bool:
    """
    Check if two squares are adjacent (including diagonally).
    Returns True if they are adjacent, False otherwise.
    """
    file1, rank1 = ord(square1[0]), int(square1[1])
    file2, rank2 = ord(square2[0]), int(square2[1])
    file_diff = abs(file1 - file2)
    rank_diff = abs(rank1 - rank2)
    # Adjacent if both differences are <= 1 and not both zero
    return (file_diff <= 1 and rank_diff <= 1) and not (file_diff == 0 and rank_diff == 0)

def select_non_adjacent_squares(squares_pool: list, num_squares: int) -> list:
    """
    Select non-adjacent squares from the given pool.
    """
    if num_squares == 0:
        return []
    selected = []
    available = squares_pool.copy()
    for _ in range(num_squares):
        if not available:
            break
        # Try to find a square that's not adjacent to any already selected
        valid_choices = []
        for sq in available:
            is_valid = True
            for sel_sq in selected:
                if are_squares_adjacent(sq, sel_sq):
                    is_valid = False
                    break
            if is_valid:
                valid_choices.append(sq)
        if valid_choices:
            chosen = random.choice(valid_choices)
            selected.append(chosen)
            available.remove(chosen)
        else:
            # If no non-adjacent squares available, pick any remaining
            chosen = random.choice(available)
            selected.append(chosen)
            available.remove(chosen)
    return selected

def square_to_index(square: str) -> Tuple[int, int]:
    """Convert square like 'E4' to (row, col) indices (0-7)."""
    file = ord(square[0]) - ord('A')
    rank = int(square[1]) - 1
    return (rank, file)

def index_to_square(row: int, col: int) -> str:
    """Convert (row, col) indices (0-7) to square like 'E4'."""
    if 0 <= row < 8 and 0 <= col < 8:
        file = chr(ord('A') + col)
        rank = str(row + 1)
        return file + rank
    return None

def get_attacked_squares(piece_type: str, square: str) -> set:
    """
    Get the set of squares attacked by a piece of given type on the given square.
    Simplified movement rules for endgame plausibility.
    """
    row, col = square_to_index(square)
    attacked = set()

    if "pawn" in piece_type:
        direction = 1 if "white" in piece_type else -1
        # Pawns capture diagonally forward
        for dc in [-1, 1]:
            new_row, new_col = row + direction, col + dc
            target_sq = index_to_square(new_row, new_col)
            if target_sq:
                attacked.add(target_sq)

    elif "knight" in piece_type:
        knight_moves = [(-2,-1), (-2,1), (-1,-2), (-1,2), (1,-2), (1,2), (2,-1), (2,1)]
        for dr, dc in knight_moves:
            new_row, new_col = row + dr, col + dc
            target_sq = index_to_square(new_row, new_col)
            if target_sq:
                attacked.add(target_sq)

    elif "king" in piece_type:
        for dr in [-1, 0, 1]:
            for dc in [-1, 0, 1]:
                if dr == 0 and dc == 0:
                    continue
                new_row, new_col = row + dr, col + dc
                target_sq = index_to_square(new_row, new_col)
                if target_sq:
                    attacked.add(target_sq)

    elif "rook" in piece_type or "queen" in piece_type:
        # Rook-like moves (horizontal/vertical)
        for dr, dc in [(0,1), (1,0), (0,-1), (-1,0)]:
            r, c = row + dr, col + dc
            while 0 <= r < 8 and 0 <= c < 8:
                attacked.add(index_to_square(r, c))
                r += dr
                c += dc

    if "bishop" in piece_type or "queen" in piece_type:
        # Bishop-like moves (diagonal)
        for dr, dc in [(1,1), (1,-1), (-1,1), (-1,-1)]:
            r, c = row + dr, col + dc
            while 0 <= r < 8 and 0 <= c < 8:
                attacked.add(index_to_square(r, c))
                r += dr
                c += dc

    return attacked

def get_path_squares(from_square: str, to_square: str) -> list:
    """
    Get the list of squares between from_square and to_square (exclusive).
    Returns empty list if not in a straight line (rook/bishop/queen path).
    """
    from_row, from_col = square_to_index(from_square)
    to_row, to_col = square_to_index(to_square)

    path = []

    # Check if same square
    if from_square == to_square:
        return path

    # Determine direction
    dr = 0
    dc = 0
    if to_row > from_row:
        dr = 1
    elif to_row < from_row:
        dr = -1

    if to_col > from_col:
        dc = 1
    elif to_col < from_col:
        dc = -1

    # Must be horizontal, vertical, or diagonal
    if not ((dr == 0 and dc != 0) or (dr != 0 and dc == 0) or (abs(dr) == abs(dc))):
        return path

    # Walk the path
    current_row = from_row + dr
    current_col = from_col + dc
    while (current_row, current_col) != (to_row, to_col):
        sq = index_to_square(current_row, current_col)
        if sq:
            path.append(sq)
        current_row += dr
        current_col += dc

    return path

def is_path_clear(from_square: str, to_square: str, occupied_squares: set) -> bool:
    """
    Check if the path between from_square and to_square is clear of any occupied squares.
    """
    if "pawn" in from_square or "knight" in from_square or "king" in from_square:
        return True  # No path to check for these pieces

    path = get_path_squares(from_square, to_square)
    for sq in path:
        if sq in occupied_squares:
            return False
    return True

@register()
def create_chess_pieces() -> Shape:
    """
    Create a set of chess pieces for an endgame using a new generation logic:
    1. First, place a 'capturing' piece randomly in the lower half (ranks 1-4).
    2. Then, place an enemy piece on a square it can capture.
    3. For sliding pieces (rook/queen/bishop), ensure the path is clear.
    4. Add 2-4 additional random pieces (ensuring total <=7 and both kings present).
    5. Ensure all lower half pieces are non-adjacent.

    All loops use bounded retry limits to prevent infinite loops.
    Includes SIGALRM timeout as a safety net against any remaining hidden hangs.
    """
    import random

    MAX_MAIN_RETRIES = 50  # Increased from 30 to reduce fallback frequency

    def _generate_once():
        """Single generation attempt. Returns (success, result_or_None)."""
        all_piece_types = ["pawn_white", "rook_white", "knight_white", "bishop_white", "queen_white",
                          "pawn_black", "rook_black", "knight_black", "bishop_black", "queen_black"]
        capturing_piece_type = random.choice(all_piece_types)
        is_capturing_white = "white" in capturing_piece_type

        capturing_square = random.choice(LOWER_HALF_SQUARES)

        attacked_squares = get_attacked_squares(capturing_piece_type, capturing_square)
        valid_capture_squares = [sq for sq in attacked_squares if sq in SQUARE_TO_COORD.keys()]
        if not valid_capture_squares:
            return False, None

        captured_square = random.choice(valid_capture_squares)
        captured_piece_type = "king_black" if is_capturing_white else "king_white"

        all_pieces_info = [
            (capturing_piece_type, capturing_square),
            (captured_piece_type, captured_square)
        ]
        occupied_squares = {capturing_square, captured_square}

        has_white_king = any("king_white" in pt for pt, _ in all_pieces_info)
        has_black_king = any("king_black" in pt for pt, _ in all_pieces_info)

        num_additional = random.randint(2, 4)
        max_total = 7
        pieces_to_add = min(num_additional, max_total - len(all_pieces_info))

        all_available_types = (
            ["pawn_white", "rook_white", "knight_white", "bishop_white", "queen_white"]
            + ["pawn_black", "rook_black", "knight_black", "bishop_black", "queen_black"]
        )

        for _ in range(pieces_to_add):
            if len(all_pieces_info) >= max_total:
                break
            piece_type = random.choice(all_available_types)
            available = [sq for sq in SQUARE_TO_COORD.keys() if sq not in occupied_squares]
            if not available:
                break
            lower_avail = [sq for sq in available if sq in LOWER_HALF_SQUARES]
            cur_lower = sum(1 for _, sq in all_pieces_info if sq in LOWER_HALF_SQUARES)
            square = random.choice(lower_avail) if lower_avail and cur_lower < 4 else random.choice(available)
            all_pieces_info.append((piece_type, square))
            occupied_squares.add(square)

        if not has_white_king and len(all_pieces_info) < max_total:
            av = [sq for sq in SQUARE_TO_COORD.keys() if sq not in occupied_squares]
            if av:
                all_pieces_info.append(("king_white", random.choice(av)))
        if not has_black_king and len(all_pieces_info) < max_total:
            av = [sq for sq in SQUARE_TO_COORD.keys() if sq not in occupied_squares]
            if av:
                all_pieces_info.append(("king_black", random.choice(av)))

        if not _ensure_lower_half_non_adjacent(all_pieces_info, occupied_squares):
            return False, None

        # Validate capture
        capture_valid = False
        for pt, sq in all_pieces_info:
            if pt == capturing_piece_type and sq == capturing_square:
                for cpt, csq in all_pieces_info:
                    if cpt == captured_piece_type and csq == captured_square:
                        if is_path_clear(capturing_square, captured_square,
                                        occupied_squares - {capturing_square, captured_square}):
                            capture_valid = True
                        break
                break

        if not capture_valid:
            return False, None

        # Build shapes
        all_pieces = []
        for piece_type, square in all_pieces_info:
            piece_oid = CHESS_PIECE_MAPPING[piece_type]
            piece_shape = library_call(
                "usd", oid=piece_oid,
                keywords=[piece_type, "white" if "white" in piece_type else "black",
                         "chess_piece", f"position_{square}"],
            )
            x, y = SQUARE_TO_COORD[square]
            piece_t = transform_shape(piece_shape, translation_matrix([x, y, 0.05]))
            center = compute_shape_center(piece_t)
            angle = random.uniform(-math.pi, math.pi)
            all_pieces.append(transform_shape(piece_t, rotation_matrix(angle, direction=(0, 0, 1), point=center)))
        return True, (concat_shapes(*all_pieces) if all_pieces else [])

    # --- Bounded retry loop ---
    for _ in range(MAX_MAIN_RETRIES):
        ok, result = _generate_once()
        if ok:
            return result

    # Fallback: deterministic, guaranteed to terminate
    return create_chess_pieces_fallback()


def _ensure_lower_half_non_adjacent(all_pieces_info: list, occupied_squares: set) -> bool:
    """
    Ensure all pieces in the lower half are non-adjacent.
    Returns True if successful, False if impossible to satisfy.
    Uses bounded retries to prevent infinite loops.
    """
    MAX_FIX_ATTEMPTS = 50

    lower_half_pieces = [(pt, sq) for pt, sq in all_pieces_info if sq in LOWER_HALF_SQUARES]
    if len(lower_half_pieces) <= 1:
        return True

    lower_squares = [sq for _, sq in lower_half_pieces]

    for _ in range(MAX_FIX_ATTEMPTS):
        # Check if any adjacent pairs remain
        has_adjacent = False
        for i in range(len(lower_squares)):
            for j in range(i + 1, len(lower_squares)):
                if are_squares_adjacent(lower_squares[i], lower_squares[j]):
                    has_adjacent = True
                    # Try to move the later piece (j) to a non-adjacent square
                    piece_idx = None
                    for idx, (pt, sq) in enumerate(all_pieces_info):
                        if sq == lower_squares[j]:
                            piece_idx = idx
                            break

                    if piece_idx is None:
                        break

                    # Find all squares not adjacent to any remaining lower half squares
                    candidate_squares = [
                        sq for sq in SQUARE_TO_COORD.keys()
                        if sq not in occupied_squares
                        and not any(are_squares_adjacent(sq, other_sq)
                                    for k, other_sq in enumerate(lower_squares)
                                    if k != j)
                    ]

                    if candidate_squares:
                        new_square = random.choice(candidate_squares)
                        old_square = lower_squares[j]
                        # Update lower_squares and all_pieces_info BEFORE modifying occupied_squares
                        lower_squares[j] = new_square
                        all_pieces_info[piece_idx] = (all_pieces_info[piece_idx][0], new_square)
                        # Now safe to update occupied_squares
                        occupied_squares.discard(old_square)
                        occupied_squares.add(new_square)
                    else:
                        # No valid position found, fail
                        return False
                    break
            if has_adjacent:
                break

        if not has_adjacent:
            return True

    return False

def create_chess_pieces_fallback() -> Shape:
    """Fallback function using the previous logic if the new logic fails."""
    import random
    # Initialize piece lists with exactly one king each
    white_pieces = ["king_white"]
    black_pieces = ["king_black"]
    # Determine additional pieces for each color (0-4 additional since king is already included)
    max_white_additional = 4  # 5 total - 1 king = 4 additional
    max_black_additional = 4  # 5 total - 1 king = 4 additional
    max_total_additional = 5  # 7 total - 2 kings = 5 additional
    # Randomly determine additional pieces while respecting constraints
    num_white_additional = random.randint(0, max_white_additional)
    num_black_additional = random.randint(0, min(max_black_additional, max_total_additional - num_white_additional))
    # Ensure we don't exceed total limit
    if num_white_additional + num_black_additional > max_total_additional:
        # Adjust if needed
        excess = (num_white_additional + num_black_additional) - max_total_additional
        if num_black_additional >= excess:
            num_black_additional -= excess
        else:
            num_white_additional -= excess - num_black_additional
            num_black_additional = 0
    # Add white additional pieces
    white_piece_types = ["pawn_white", "rook_white", "knight_white", "bishop_white", "queen_white"]
    for _ in range(num_white_additional):
        piece_type = random.choice(white_piece_types)
        white_pieces.append(piece_type)
    # Add black additional pieces
    black_piece_types = ["pawn_black", "rook_black", "knight_black", "bishop_black", "queen_black"]
    for _ in range(num_black_additional):
        piece_type = random.choice(black_piece_types)
        black_pieces.append(piece_type)
    # Combine all pieces with their colors
    all_pieces_with_color = []
    for piece in white_pieces:
        all_pieces_with_color.append((piece, "white"))
    for piece in black_pieces:
        all_pieces_with_color.append((piece, "black"))
    # Now handle lower half constraint: need 2-4 pieces total in lower half
    total_pieces = len(all_pieces_with_color)
    min_lower = 2
    max_lower = min(4, total_pieces)  # Can't have more lower pieces than total pieces
    if total_pieces < min_lower:
        num_lower_pieces = total_pieces
    else:
        num_lower_pieces = random.randint(min_lower, max_lower)
    # Select non-adjacent squares for lower half
    lower_squares = select_non_adjacent_squares(LOWER_HALF_SQUARES, num_lower_pieces)
    # Assign pieces to positions
    all_pieces_info = []
    available_squares = set(SQUARE_TO_COORD.keys())
    # First assign lower half pieces
    for i, square in enumerate(lower_squares):
        if i < len(all_pieces_with_color):
            piece_type, color = all_pieces_with_color[i]
            all_pieces_info.append((piece_type, square))
            available_squares.remove(square)
    # Assign remaining pieces to upper half or any remaining squares
    remaining_pieces = all_pieces_with_color[num_lower_pieces:]
    for piece_type, color in remaining_pieces:
        if available_squares:
            square = random.choice(list(available_squares))
            all_pieces_info.append((piece_type, square))
            available_squares.remove(square)

    # Create shapes for all pieces with height adjustment and random rotation
    all_pieces = []
    for piece_type, square in all_pieces_info:
        piece_oid = CHESS_PIECE_MAPPING[piece_type]
        piece_shape = library_call(
            "usd",
            oid=piece_oid,
            keywords=[piece_type, "white" if "white" in piece_type else "black", "chess_piece", f"position_{square}"],
        )
        x, y = SQUARE_TO_COORD[square]
        piece_transformed = transform_shape(piece_shape, translation_matrix([x, y, 0.05]))
        piece_center = compute_shape_center(piece_transformed)
        random_angle = random.uniform(-math.pi, math.pi)
        piece_final = transform_shape(
            piece_transformed, rotation_matrix(random_angle, direction=(0, 0, 1), point=piece_center)
        )
        all_pieces.append(piece_final)
    return concat_shapes(*all_pieces) if all_pieces else []

