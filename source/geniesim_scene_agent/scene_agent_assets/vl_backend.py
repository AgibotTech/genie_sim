"""Adapter for the bundled Qwen3-VL multi-view video embedder."""

from __future__ import annotations

import importlib.util
from pathlib import Path

import numpy as np


VIDEO_INSTRUCTION = (
    "Extract embedding for the foreground object only. Ignore all background elements "
    "(white/black backgrounds). Encode only the object's intrinsic, viewpoint-invariant "
    "visual features: shape, texture, material properties, structural details and usage. "
    "The provided text's semantic name and semantic description are the description "
    "about the object generated by other VLM, BUT THE VISION IS FIRST PRIORITY."
)
TEXT_INSTRUCTION = (
    "Extract embedding for the text. Encode only the text described object's intrinsic: "
    "shape, texture, material properties, structural details and usage."
)


class QwenVLBackend:
    def __init__(self, model_path: str | Path, model=None):
        self.model_path = Path(model_path).expanduser().resolve()
        self.model_id = str(self.model_path)
        self._model = model

    def _load_model(self):
        if self._model is not None:
            return self._model
        if not self.model_path.is_dir():
            raise FileNotFoundError(f"Qwen3-VL model is missing: {self.model_path}")
        import torch

        if not torch.cuda.is_available():
            raise RuntimeError("Qwen3-VL video embedding requires a CUDA GPU; use catalog-search instead")
        from .qwen3_vl_embedding import Qwen3VLEmbedder
        attention = "flash_attention_2" if importlib.util.find_spec("flash_attn") else "sdpa"
        self._model = Qwen3VLEmbedder(
            model_name_or_path=str(self.model_path), fps=6,
            torch_dtype=torch.bfloat16, attn_implementation=attention,
        )
        return self._model

    def embed_video(self, video_path: str, semantic_name: str, description: str) -> np.ndarray:
        entry = {"video": str(video_path), "fps": 6, "instruction": VIDEO_INSTRUCTION,
                 "text": f"semantic_name: {semantic_name};semantic_description: {description};"}
        value = self._load_model().process([entry])[0]
        if hasattr(value, "detach"):
            value = value.detach().float().cpu().numpy()
        return np.asarray(value, dtype=np.float32)

    def embed_text(self, query: str) -> np.ndarray:
        value = self._load_model().process([{"text": query, "instruction": TEXT_INSTRUCTION}])[0]
        if hasattr(value, "detach"):
            value = value.detach().float().cpu().numpy()
        return np.asarray(value, dtype=np.float32)
