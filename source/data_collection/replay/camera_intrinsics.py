def get_intrinsic_for_camera(robot_name: str, camera_name: str) -> dict:
    """Return intrinsics for a robot camera, or an empty dict if unknown."""
    name = robot_name or ""
    if "ARX" in name:
        robot_type = "ARX"
    elif "G2" in name:
        robot_type = "G2"
    elif "G1" in name:
        robot_type = "G1"
    else:
        robot_type = ""
    if not robot_type or robot_type not in CAMERA_INTRINSICS:
        return {}
    by_camera = CAMERA_INTRINSICS[robot_type]
    return dict(by_camera.get(camera_name, {}))
